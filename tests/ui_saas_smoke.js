// Headless UI smoke for the SaaS flow: pricing PayPal buttons -> register -> PayPal upgrade request -> admin approves.
const { spawn } = require("child_process");
const path = require("path");
const puppeteer = require(process.env.PUPPETEER || "puppeteer-core");
const BASE = process.env.BASE || "http://localhost:8099";
const ADMIN = process.env.ADMIN || "abaudii12@gmail.com";
const ADMIN_PW = process.env.ADMIN_PW || "AdminPass123!";
const SHOTS = process.env.SHOTS || "/workspace/shots";
const ok = (c, m) => { if (!c) { console.error("✘ " + m); process.exit(1); } console.log("✔ " + m); };
(async () => {
  const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
  const p = await b.newPage(); await p.setViewport({ width: 1280, height: 900 });
  const errs = []; p.on("pageerror", (e) => errs.push(p.url() + " " + e.message.slice(0, 60)));
  for (const u of ["/", "/pricing/", "/marketplace/", "/docs/", "/docs/connect/", "/docs/bots/", "/docs/marketplace/", "/docs/api/", "/docs/tunnels/", "/docs/webhooks/"]) {
    const r = await p.goto(BASE + u, { waitUntil: "networkidle0" }); ok(r.status() === 200, `GET ${u} 200`);
  }
  await p.goto(BASE + "/marketplace/", { waitUntil: "networkidle0" });
  const cards = await p.$$eval("button, a", (els) => els.filter((e) => /Start free to use this master/.test(e.textContent)).length);
  ok(cards >= 3, `public marketplace shows ${cards} masters`);
  await p.goto(BASE + "/pricing/", { waitUntil: "networkidle0" });
  const pp = await p.$$eval("a[href*='paypal.me']", (a) => a.map((x) => x.href));
  ok(pp.includes("https://paypal.me/BunnyOnMoney/19USD") && pp.includes("https://paypal.me/BunnyOnMoney/79USD"), "pricing PayPal buttons " + pp.join(" "));
  const wa = await p.$$eval("a[href*='wa.me/966567009846']", (a) => a.length); ok(wa >= 3, `WhatsApp links on pricing: ${wa}`);
  await p.screenshot({ path: SHOTS + "/pricing.png", fullPage: true });
  // register user
  const email = `ui${Date.now()}@example.com`;
  await p.goto(BASE + "/login/?mode=register&plan=PRO", { waitUntil: "networkidle0" });
  await p.type("input[type=email]", email); await p.type("input[type=password]", "Passw0rd!123");
  await p.click("form button.btn-primary"); await p.waitForFunction(() => !location.pathname.startsWith("/login"), { timeout: 15000 });
  await p.goto(BASE + "/billing/", { waitUntil: "networkidle0" });
  await p.waitForSelector("#ref", { timeout: 10000 });
  const bp = await p.$$eval("a[href*='paypal.me']", (a) => a.map((x) => x.href)); ok(bp.some((h) => /BunnyOnMoney\/(19|79)USD/.test(h)), "billing PayPal button " + bp[0]);
  await p.type("#ref", "PAYID-UI-TEST-123");
  const [btn] = await p.$$("xpath/.//button[contains(., 'Submit PayPal payment')]"); ok(!!btn, "submit PayPal button present");
  await btn.click(); await p.waitForFunction(() => document.body.innerText.includes("pending admin approval"), { timeout: 10000 });
  ok(true, "upgrade request pending shown"); await p.screenshot({ path: SHOTS + "/billing.png", fullPage: true });
  // link a bot in the UI, run the real SDK with the shown token, make it a master
  await p.goto(BASE + "/bots/", { waitUntil: "networkidle0" });
  await p.type("#bname", "ui-hermes");
  const [linkBtn] = await p.$$("xpath/.//button[normalize-space(.)='Link bot']"); await linkBtn.click();
  await p.waitForFunction(() => document.body.innerText.includes("Copy the bot token now"), { timeout: 10000 });
  const tok = await p.$$eval("pre code", (els) => els.map((e) => e.textContent).find((t) => /^bbt_/.test(t)));
  ok(tok && tok.startsWith("bbt_"), "bot token shown once in UI");
  await p.screenshot({ path: SHOTS + "/bots.png", fullPage: true });
  const sdk = spawn("python3", [path.join(__dirname, "..", "connector", "bridgebot_sdk.py"), "--server", BASE, "--token", tok, "--exec", "echo [hermes] customer support ready: {text}"], { stdio: "ignore" });
  await p.goto(BASE + "/marketplace/", { waitUntil: "networkidle0" });
  const [mm] = await p.$$("xpath/.//button[contains(., 'Make my bot a master')]"); ok(!!mm, "Make my bot a master button");
  await mm.click();
  await p.waitForFunction(() => document.body.innerText.includes("GRADUATED"), { timeout: 30000 });
  ok(true, "one click → bot GRADUATED (welcome + inject + test automatic)");
  await p.screenshot({ path: SHOTS + "/marketplace.png", fullPage: true });
  const [og] = await p.$$("xpath/.//a[contains(., 'Open group')]"); await og.click();
  await p.waitForFunction(() => document.body.innerText.includes("🎓"), { timeout: 15000 });
  ok(true, "group feed shows graduation");
  await p.screenshot({ path: SHOTS + "/group.png", fullPage: true });
  sdk.kill();
  await p.goto(BASE + "/bots/", { waitUntil: "networkidle0" });
  await p.waitForFunction(() => document.body.innerText.includes("Master persona"), { timeout: 10000 });
  ok(true, "bot shows cloned master persona + skill");
  // tunnels: real connector + real local http.server, created through the UI
  const fs = require("fs"); const os = require("os");
  const site = fs.mkdtempSync(path.join(os.tmpdir(), "bbsite-")); fs.writeFileSync(path.join(site, "index.html"), "<h1>hello from my laptop</h1>");
  const lport = 18000 + Math.floor(Math.random() * 1000);
  const web = spawn("python3", ["-m", "http.server", String(lport), "--bind", "127.0.0.1", "--directory", site], { stdio: "ignore" });
  const created = await p.evaluate(async (base) => {
    const t = localStorage.getItem("bridgebot_token");
    const r = await fetch(base + "/api/connectors", { method: "POST", headers: { Authorization: "Bearer " + t, "Content-Type": "application/json" }, body: JSON.stringify({ machine_name: "ui-laptop" }) });
    return r.json();
  }, BASE);
  ok(created.api_key && created.api_key.startsWith("bbk_"), "connector created for tunnel test");
  const cfgDir = fs.mkdtempSync(path.join(os.tmpdir(), "bbconn-"));
  const conn = spawn("python3", [path.join(__dirname, "..", "connector", "local_connector.py"), "--server", BASE, "--api-key", created.api_key, "--machine-name", "ui-laptop", "--config", path.join(cfgDir, "c.json"), "--skills-dir", path.join(cfgDir, "skills")], { stdio: "ignore" });
  await p.goto(BASE + "/tunnels/", { waitUntil: "networkidle0" });
  await p.waitForFunction(() => document.querySelector("select option") && document.body.innerText.includes("New tunnel"), { timeout: 15000 });
  await p.waitForFunction(() => [...document.querySelectorAll("select option")].some((o) => o.textContent.includes("🟢")), { timeout: 20000 }).catch(() => {});
  const portInput = await p.$("input[type=number]"); await portInput.click({ clickCount: 3 }); await portInput.type(String(lport));
  const [mk] = await p.$$("xpath/.//button[normalize-space(.)='Create tunnel']"); await mk.click();
  await p.waitForSelector("[data-tunnel] a[href*='/t/']", { timeout: 10000 });
  const turl = await p.$eval("[data-tunnel] a[href*='/t/']", (a) => a.href);
  ok(/\/t\/[a-z0-9-]+\/$/.test(turl), "tunnel created in UI → " + turl);
  await p.waitForFunction(() => document.body.innerText.includes("ONLINE"), { timeout: 20000 });
  await p.screenshot({ path: SHOTS + "/tunnels.png", fullPage: true });
  const tp = await b.newPage(); const tr = await tp.goto(turl, { waitUntil: "load" });
  const tbody = await tp.evaluate(() => document.body.innerText);
  ok(tr.status() === 200 && tbody.includes("hello from my laptop"), "public tunnel URL serves the local http.server page");
  await tp.close(); conn.kill(); web.kill();
  // admin
  await p.evaluate(() => localStorage.clear());
  await p.goto(BASE + "/login/", { waitUntil: "networkidle0" });
  await p.type("input[type=email]", ADMIN); await p.type("input[type=password]", ADMIN_PW);
  await p.click("form button.btn-primary"); await p.waitForFunction(() => !location.pathname.startsWith("/login"), { timeout: 15000 });
  await p.goto(BASE + "/admin/", { waitUntil: "networkidle0" });
  await p.waitForFunction(() => document.body.innerText.includes("Users"), { timeout: 10000 });
  await p.screenshot({ path: SHOTS + "/admin.png", fullPage: true });
  const [mt] = await p.$$("xpath/.//button[normalize-space(.)='Marketplace']"); await mt.click();
  await p.waitForFunction(() => document.body.innerText.includes("Publish a new Master Bot") && document.body.innerText.includes("Sales Closer Elite"), { timeout: 10000 });
  ok(true, "admin marketplace tab lists masters + publish form");
  await p.screenshot({ path: SHOTS + "/admin_marketplace.png", fullPage: true });
  const tabs = await p.$$("xpath/.//button[contains(., 'Upgrade')]"); if (tabs[0]) await tabs[0].click();
  await p.waitForFunction(() => document.body.innerText.includes("PAYID-UI-TEST-123"), { timeout: 10000 }); ok(true, "admin sees PayPal txn id");
  await p.screenshot({ path: SHOTS + "/admin_upgrades.png", fullPage: true });
  const [ap] = await p.$$("xpath/.//button[normalize-space(.)='Approve' or starts-with(normalize-space(.),'Approve')]"); ok(!!ap, "approve button");
  p.on("dialog", (d) => d.accept()); await ap.click(); await new Promise((r) => setTimeout(r, 1500));
  const st = await p.evaluate(async (em) => { const t = localStorage.getItem("bridgebot_token"); const r = await fetch("/api/admin/users?q=" + encodeURIComponent(em), { headers: { Authorization: "Bearer " + t } }); return r.json(); }, email);
  const u = (st.users || st).find((x) => x.email === email); ok(u && u.plan_id === "PRO", "user upgraded to PRO by admin: " + (u && u.plan_id));
  ok(errs.length === 0, "no page errors " + errs.join(";")); await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
